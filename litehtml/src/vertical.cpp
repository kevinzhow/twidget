#include "html.h"
#include "vertical.h"

namespace litehtml
{
    bool upright_in_vertical(char32_t cp)
    {
        if(cp < 0xA7)
            return false;
        struct range
        {
            char32_t first, last;
        };
        // Sorted, from Unicode 16's VerticalOrientation.txt (U, Tu, Tr), merged where small R gaps do not matter for
        // Japanese text.
        static const range upright[] = {
            {0x00A7, 0x00A7}, {0x00A9, 0x00A9}, {0x00AE, 0x00AE}, {0x00B1, 0x00B1}, {0x00BC, 0x00BE}, {0x00D7, 0x00D7},
            {0x00F7, 0x00F7}, {0x02EA, 0x02EB}, {0x1100, 0x11FF}, {0x1401, 0x167F}, {0x18B0, 0x18FF}, {0x2016, 0x2016},
            {0x2020, 0x2021}, {0x2025, 0x2026}, {0x2030, 0x2031}, {0x203B, 0x203C}, {0x2042, 0x2042}, {0x2047, 0x2049},
            {0x2051, 0x2051}, {0x2065, 0x2065}, {0x20DD, 0x20E0}, {0x20E2, 0x20E4}, {0x2100, 0x2101}, {0x2103, 0x2109},
            {0x210F, 0x210F}, {0x2113, 0x2114}, {0x2116, 0x2117}, {0x211E, 0x2123}, {0x2125, 0x2125}, {0x2127, 0x2127},
            {0x2129, 0x2129}, {0x212E, 0x212E}, {0x2135, 0x213F}, {0x2145, 0x214A}, {0x214C, 0x214D}, {0x214F, 0x2189},
            {0x218C, 0x218F}, {0x221E, 0x221E}, {0x2234, 0x2235}, {0x2300, 0x2307}, {0x230C, 0x231F}, {0x2324, 0x232B},
            {0x237D, 0x239A}, {0x23BE, 0x23CD}, {0x23CF, 0x23CF}, {0x23D1, 0x23DB}, {0x23E2, 0x2422}, {0x2424, 0x24FF},
            {0x25A0, 0x2619}, {0x2620, 0x2767}, {0x2776, 0x2793}, {0x2B12, 0x2B2F}, {0x2B50, 0x2B59}, {0x2BB8, 0x2BFF},
            {0x2E3A, 0x2E3B}, {0x2E80, 0xA4CF}, {0xA960, 0xA97F}, {0xAC00, 0xD7FF}, {0xE000, 0xFAFF}, {0xFE10, 0xFE1F},
            {0xFE30, 0xFE6F}, {0xFF01, 0xFF60}, {0xFFE0, 0xFFE7}, {0x1F000, 0x1FAFF}, {0x20000, 0x3FFFD},
        };
        size_t lo = 0, hi = sizeof(upright) / sizeof(upright[0]);
        while(lo < hi)
        {
            size_t mid = (lo + hi) / 2;
            if(cp < upright[mid].first)
                hi = mid;
            else if(cp > upright[mid].last)
                lo = mid + 1;
            else
                return true;
        }
        return false;
    }
} // namespace litehtml
